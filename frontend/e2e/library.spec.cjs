test('catalog brand picker shares logos and search while limiting choices to the library', async ({page}, info) => {
  await page.goto('/sets?page=2');
  const trigger = page.getByRole('button', {name:'筛选品牌：全部品牌'});
  await expect(trigger).toBeEnabled();
  await trigger.click();
  const dialog = page.getByRole('dialog', {name:'选择品牌', exact:true});
  await expect(dialog).toBeVisible();
  expect((await dialog.locator('.brand-search').boundingBox()).height).toBe(48);
  await expect(dialog.locator('.brand-option')).toHaveCount(41);
  await expect(dialog.getByRole('button', {name:'其他，自定义品牌'})).toHaveCount(0);
  await expect(dialog.getByRole('button', {name:'全部品牌', exact:true})).toHaveAttribute('aria-pressed','true');
  const bmw = dialog.getByRole('button', {name:'宝马 BMW', exact:true});
  await bmw.scrollIntoViewIfNeeded();
  await expect.poll(()=>bmw.locator('img').evaluate(img=>img.naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({path:info.outputPath('catalog-brand-picker.png')});
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await trigger.click();
  await dialog.getByRole('textbox', {name:'搜索品牌', exact:true}).fill('萤火虫');
  await expect(dialog.getByText('没有匹配的品牌', {exact:true})).toBeVisible();
  await dialog.getByRole('textbox', {name:'搜索品牌', exact:true}).fill('BMW');
  await expect(dialog.locator('.brand-option')).toHaveCount(1);
  await dialog.getByRole('textbox', {name:'搜索品牌', exact:true}).press('Enter');
  await expect(dialog).not.toBeVisible();
  await expect(page).toHaveURL(/\/sets\?brand=bmw$/);
  await expect(page.getByRole('button', {name:'筛选品牌：宝马'})).toBeVisible();
  await page.screenshot({path:info.outputPath('catalog-brand-selected.png')});
  await page.getByRole('button', {name:'清除品牌筛选', exact:true}).click();
  await expect(trigger).toBeVisible();
  await expect(page).toHaveURL(/\/sets$/);
  await trigger.click();
  await dialog.getByRole('textbox', {name:'搜索品牌', exact:true}).fill('英国联合设备');
  await dialog.getByRole('button', {name:'英国联合设备（AEC） AEC', exact:true}).click();
  await expect(page.getByRole('button', {name:'筛选品牌：英国联合设备（AEC）'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button', {name:'筛选品牌：英国联合设备（AEC）'}).click();
  await dialog.getByRole('button', {name:'显示全部品牌', exact:true}).click();
  await expect(trigger).toBeVisible();
});

test('Chinese catalog combines all filters, preserves navigation, and downloads the exact IO', async ({ page, request }, info) => {
  const response = await request.get('/api/v1/sets/library?q=42226-1');
  const { models: [model] } = await response.json();
  expect(model.name_zh).toBe('宝马 M4 GT3 EVO 赛车');
  await page.goto('/sets');
  await page.getByRole('button', {name:'筛选品牌：全部品牌'}).click();
  await page.getByRole('textbox', {name:'搜索品牌', exact:true}).fill('宝马');
  await page.getByRole('button', {name:'宝马 BMW', exact:true}).click();
  await page.getByRole('combobox', {name:'筛选车辆类型'}).selectOption('race_car');
  if (model.release_year) await page.getByRole('combobox', {name:'筛选年份'}).selectOption(`release:${model.release_year}`);
  await page.getByRole('textbox', {name:'搜索车型', exact:true}).fill('M4');
  await expect(page).toHaveURL(/q=M4/);
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await expect(page.getByRole('heading', {name:model.name_zh, exact:true})).toBeVisible();
  const pending = page.waitForEvent('download');
  await page.getByRole('link', {name:'下载 .io', exact:true}).click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe(model.filename);
  const target = info.outputPath(model.filename);
  await download.saveAs(target);
  expect(createHash('sha256').update(await fs.readFile(target)).digest('hex')).toBe(model.sha256);
  await page.screenshot({path: info.outputPath('chinese-filter-download.png')});
  await page.getByRole('link', {name:'查看模型', exact:true}).click();
  await expect(page.getByRole('heading', {name:model.name_zh, exact:true})).toBeVisible();
  await page.getByRole('link', {name:'车型库', exact:true}).click();
  await expect(page.getByRole('button', {name:'筛选品牌：宝马'})).toBeVisible();
  await expect(page.getByRole('textbox', {name:'搜索车型', exact:true})).toHaveValue('M4');
  await page.getByRole('textbox', {name:'搜索车型', exact:true}).fill('不存在的车型ZZZ');
  await expect(page.getByRole('heading', {name:'没有相关车型'})).toBeVisible();
  await page.getByRole('button', {name:'清除筛选'}).first().click();
  await expect(page.getByRole('button', {name:'筛选品牌：全部品牌'})).toBeVisible();
  await expect(page.locator('.catalog-item')).toHaveCount(24);
});

test('actual Countach and F40 geometry renders, orbits, and remains framed', async ({page, request}, info) => {
  test.setTimeout(180000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  for (const set of ['10337-1','10248-1']) {
    const {models:[model]} = await (await request.get(`/api/v1/sets/library?q=${set}`)).json();
    await page.goto(`/sets/${model.id}`);
    const canvas = page.locator('.library-canvas canvas');
    await expect(canvas).toBeVisible({timeout:120000});
    await expect(page.getByRole('button', {name:'恢复视角', exact:true})).toBeVisible();
    const before = await canvas.screenshot();
    const png = PNG.sync.read(before);
    let foreground = 0;
    for (let i=0;i<png.data.length;i+=4) {
      if (Math.abs(png.data[i]-245)+Math.abs(png.data[i+1]-245)+Math.abs(png.data[i+2]-247)>42) foreground++;
    }
    expect(foreground/(png.width*png.height)).toBeGreaterThan(.015);
    expect(foreground/(png.width*png.height)).toBeLessThan(.8);
    await page.screenshot({path:info.outputPath(`${set}-3d.png`)});
    const box=await canvas.boundingBox();
    await page.mouse.move(box.x+box.width*.5,box.y+box.height*.5);
    await page.mouse.down(); await page.mouse.move(box.x+box.width*.68,box.y+box.height*.6,{steps:12}); await page.mouse.up();
    await expect.poll(async()=>createHash('sha256').update(await canvas.screenshot()).digest('hex')).not.toBe(createHash('sha256').update(before).digest('hex'));
    await page.getByRole('button',{name:'恢复视角',exact:true}).click();
    await page.getByRole('button',{name:'线框',exact:true}).click();
    await expect(page.getByRole('button',{name:'线框',exact:true})).toHaveAttribute('aria-pressed','true');
    await page.getByRole('button',{name:'线框',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await expect(canvas).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    const small=PNG.sync.read(await canvas.screenshot());
    expect(small.width).toBeGreaterThan(250);
    let smallForeground=0;
    for(let i=0;i<small.data.length;i+=4) if(Math.abs(small.data[i]-245)+Math.abs(small.data[i+1]-245)+Math.abs(small.data[i+2]-247)>42) smallForeground++;
    expect(smallForeground/(small.width*small.height)).toBeGreaterThan(.01);
    await page.screenshot({path:info.outputPath(`${set}-narrow.png`)});
    await page.setViewportSize(info.project.use.viewport);
  }
  expect(errors).toEqual([]);
});
